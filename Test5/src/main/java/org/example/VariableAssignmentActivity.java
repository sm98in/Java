package org.example;

public class VariableAssignmentActivity {
    public static void main(String[] args) {
        // 1. new variable and set a value equal to 5
        int number = 5;
        System.out.println("New value is: " + number);

        // 2. Update value
        number = 20;

        // 3. Print updated value
        System.out.println("Updated value is: " + number);
    }
}
